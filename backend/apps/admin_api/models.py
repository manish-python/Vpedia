"""Admin notifications.

A single, staff-only feed for operational events: a new student, a payment
request, a payment decision, a publication.

Design rules
------------
* **Server-controlled.** Rows are created by `apps.admin_api.notifications.notify`
  from the places that actually perform the work (the OAuth adapter, the
  payment service). There is no public or staff-writable create endpoint, so a
  client cannot forge a "payment approved" event.
* **Not business state.** A notification is a record that something happened,
  never the record itself. Deleting one loses a breadcrumb, not a purchase.
* **Staff-only.** Every route is guarded by `IsStaffUser`; a student gets 403.
"""

from __future__ import annotations

from django.db import models

from apps.core.models import TimeStampedModel


class NotificationType(models.TextChoices):
    NEW_STUDENT = "NEW_STUDENT", "New student"
    PAYMENT_REQUEST = "PAYMENT_REQUEST", "Payment request"
    PAYMENT_APPROVED = "PAYMENT_APPROVED", "Payment approved"
    PAYMENT_REJECTED = "PAYMENT_REJECTED", "Payment rejected"
    CONTENT_PUBLISHED = "CONTENT_PUBLISHED", "Content published"
    RESOURCE_PUBLISHED = "RESOURCE_PUBLISHED", "Resource published"
    SYSTEM_ALERT = "SYSTEM_ALERT", "System"


class AdminNotificationQuerySet(models.QuerySet):
    def unread(self) -> "AdminNotificationQuerySet":
        return self.filter(is_read=False)

    def recent(self) -> "AdminNotificationQuerySet":
        return self.order_by("-created_at", "-id")


class AdminNotification(TimeStampedModel):
    """One item in the admin notification feed.

    `link` is an internal admin path such as
    `/admin-panel/payments?payment=12`. It is generated by the server from the
    primary key of the record it describes, never accepted from a client, so a
    link cannot point anywhere outside the portal.
    """

    type = models.CharField(
        max_length=32, choices=NotificationType.choices, default=NotificationType.SYSTEM_ALERT
    )
    title = models.CharField(max_length=200)
    message = models.TextField(blank=True)
    link = models.CharField(max_length=300, blank=True)
    is_read = models.BooleanField(default=False, db_index=True)
    #: Set when a staff member reads it, so a dismissed item can be audited.
    read_at = models.DateTimeField(null=True, blank=True)

    objects = AdminNotificationQuerySet.as_manager()

    class Meta:
        db_table = "admin_api_notification"
        verbose_name = "admin notification"
        verbose_name_plural = "admin notifications"
        ordering = ["-created_at", "-id"]
        indexes = [models.Index(fields=["is_read", "-created_at"])]

    def __str__(self) -> str:
        return self.title

    def mark_read(self) -> None:
        from django.utils import timezone

        if self.is_read:
            return
        self.is_read = True
        self.read_at = timezone.now()
        self.save(update_fields=["is_read", "read_at", "updated_at"])